#[test]
fn mov_r64_r64_copies_all_bits() {
    // mov rcx, rax; mov r9, r14; mov r15, rax; hlt
    check(&[0x48, 0x89, 0xc1, 0x4d, 0x89, 0xf1, 0x49, 0x89, 0xc7, 0xf4]);
}

