//! Every flag producer followed by every way of consuming flags, on boundary operands. The
//! JIT keeps flags lazily (and, for a `jcc` right after an inlined ALU op, in host flags), so
//! each consumer reads them by a different route: a direct host condition, `helper_cond`, a
//! materialised eflags (`pushf`, `lahf`, `setcc`, `cmovcc`), or as a carry-in (`adc`, `sbb`,
//! `rcl`, `inc`, `dec`).
//!
//! Producers the JIT lowers inline get the full consumer set, because a following `jcc` tests
//! host flags directly and each of the 16 conditions maps differently. The rest go through
//! `helper_exec` and the interpreter's flag code, so a smaller consumer set suffices.

use super::diff_tests::{HOT_RAM, difference_in, run_serialized, seed_registers_and_memory};
use crate::testkit::*;

/// `(rax, rbx, rcx)` start values, most informative first: zero, carry and signed overflow at
/// every width, the shift-count edges (0, 63, 64) and a nibble carry.
const OPERANDS: [(u64, u64, u64); 11] = [
    (0, 0, 0),
    (u64::MAX, 1, 64),
    (i64::MAX as u64, 1, 63),
    (1 << 63, 1, 31),
    (0x8000_0000, 0x8000_0000, 32),
    (0xff, 0x01, 8),
    (0x80, 0x80, 0xff),
    (0x0f, 0x01, 5),
    (1, 1, 1),
    (0x7fff_ffff, 1, 4),
    (0xdead_beef_cafe_f00d, 0x1234_5678_9abc_def0, 13),
];
const FULL_OPERANDS: usize = 6;
const LIGHT_OPERANDS: usize = 6;
/// `jcc` conditions the light set tries: be (0x6) and l (0xc).
const LIGHT_JCC: [usize; 2] = [0x6, 0xc];
/// The first five of `FLAG_MODIFYING_CONSUMERS`: adc, sbb, inc, dec, rcl.
const LIGHT_MODIFIERS: usize = 5;

/// Runs `producer` followed by each consumer for the first `operand_count` operand triples and
/// compares the engines.
fn run_matrix(producer: &[u8], consumers: Vec<&[u8]>, operand_count: usize) {
    let mut snippets: Vec<Vec<u8>> = consumers
        .iter()
        .map(|consumer| [producer, consumer, &[HLT]].concat())
        .collect();
    // The producer alone: its own flags must survive a block exit unchanged.
    snippets.push([producer, &[HLT]].concat());
    for &(rax, rbx, rcx) in &OPERANDS[..operand_count] {
        for (index, code) in snippets.iter().enumerate() {
            let result = run_serialized(code, |harness| {
                seed_registers_and_memory(harness);
                harness.cpu.gpr[RAX] = rax;
                harness.cpu.gpr[RBX] = rbx;
                harness.cpu.gpr[RCX] = rcx;
            });
            let context = format!(
                "producer {producer:02x?} consumer #{index} rax={rax:#x} rbx={rbx:#x} rcx={rcx:#x}"
            );
            assert_eq!(
                result.interpreter_stop,
                Stop::Halted,
                "{context}: {}",
                result.interpreter.cpu.dump_regs()
            );
            if let Some(difference) = difference_in(&result, HOT_RAM) {
                panic!("{context}: {difference}");
            }
        }
    }
}

fn run_full_matrix(producer: &[u8]) {
    let consumers = JCC_CONSUMERS
        .iter()
        .map(|bytes| &bytes[..])
        .chain(std::iter::once(&PROBE_ALL[..]))
        .chain(FLAG_MODIFYING_CONSUMERS.iter().map(|(_, bytes)| *bytes))
        .collect();
    run_matrix(producer, consumers, FULL_OPERANDS);
}

fn run_light_matrix(producer: &[u8]) {
    let consumers = LIGHT_JCC
        .iter()
        .map(|&condition| &JCC_CONSUMERS[condition][..])
        .chain(std::iter::once(&PROBE_ALL[..]))
        .chain(
            FLAG_MODIFYING_CONSUMERS
                .iter()
                .take(LIGHT_MODIFIERS)
                .map(|(_, bytes)| *bytes),
        )
        .collect();
    run_matrix(producer, consumers, LIGHT_OPERANDS);
}

macro_rules! full_matrix_tests {
    ($($name:ident => $bytes:expr,)*) => {
        $(#[test]
        fn $name() {
            run_full_matrix(&$bytes);
        })*
    };
}

